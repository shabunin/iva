/**
 * iva.d.ts for a project: the elements, their props and the helpers, from
 * the compiler's own sources (so the editor knows exactly what iva takes),
 * plus jsconfig.json so VS Code & co. use it with no setup.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const COMPILER = path.join(path.dirname(fileURLToPath(import.meta.url)), 'compiler');
const UI = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'ui', 'index.tsx');

/** A source file's declarations; imports dropped (keep: those from these modules). */
function declarations(file: string, keepImportsFrom: string[] = []): string {
  const out = ts.transpileDeclaration(fs.readFileSync(path.isAbsolute(file) ? file : path.join(COMPILER, file), 'utf8'), {
    fileName: path.basename(file),
    compilerOptions: { stripInternal: true, removeComments: false, jsx: ts.JsxEmit.ReactJSX },
  });
  return out.outputText
    .split('\n')
    .filter((l) => {
      if (/^export \{\};?$/.test(l)) return false;
      if (!/^import\b/.test(l)) return true;
      return keepImportsFrom.some((m) => l.includes(`'${m}'`) || l.includes(`"${m}"`));
    })
    .join('\n')
    .trim();
}

const indent = (text: string) => text.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');

/** The globals a project file may use without importing (what the build injects). */
const GLOBALS = [
  'Project', 'Page', 'Landscape', 'Portrait', 'Subpage', 'SubpageRef', 'Button', 'Text', 'Image', 'Slider', 'Gauge', 'List', 'Input', 'Web', 'Video',
  'Gesture', 'System', 'Command', 'Feedback', 'Capture', 'OnMatch', 'Macro', 'Step', 'Token', 'Script', 'Sound', 'Theme', 'Raw', 'Box', 'Group', 'OnStart',
  'd', 'a', 's', 'l', 'cmd', 'macro', 'js', 'fa', 'draw', 'variant',
];

export function typesFile(version: string): string {
  const runtime = declarations('runtime.ts');
  const components = declarations('components.ts');
  return `// iva ${version}: types for the elements and helpers, generated by \`iva types\` - don't edit.
// Elements need no import (the build provides them); \`import { Button } from 'iva'\` works too.

declare module 'iva/jsx-runtime' {
${indent(runtime)}
}

declare module 'iva/jsx-dev-runtime' {
  export * from 'iva/jsx-runtime';
}

declare module 'iva' {
  import type { VNode, Child, Source } from 'iva/jsx-runtime';
  export type { VNode, Child, Source };
  export { Fragment } from 'iva/jsx-runtime';
${indent(components)}
}

declare module 'iva/ui' {
${indent(declarations(UI, ['iva']))}
}

${GLOBALS.map((g) => `declare const ${g}: typeof import('iva').${g};`).join('\n')}
`;
}

export const JSCONFIG = {
  compilerOptions: {
    jsx: 'react-jsx',
    jsxImportSource: 'iva',
    allowJs: true,
    checkJs: true,
    module: 'ESNext',
    moduleResolution: 'Bundler',
    target: 'ES2022',
    lib: ['ES2022'],
    noEmit: true,
    skipLibCheck: true,
  },
  include: ['**/*.jsx', '**/*.js', '**/*.tsx', '**/*.ts', 'iva.d.ts'],
  exclude: ['dist', 'scripts', 'node_modules'],
};

/** Write iva.d.ts (always) and jsconfig.json (only when missing: it's the project's). */
export function writeTypes(dir: string, version: string): string[] {
  const written = [];
  fs.writeFileSync(path.join(dir, 'iva.d.ts'), typesFile(version));
  written.push('iva.d.ts');
  const jsconfig = path.join(dir, 'jsconfig.json');
  if (!fs.existsSync(jsconfig)) {
    fs.writeFileSync(jsconfig, JSON.stringify(JSCONFIG, null, 2) + '\n');
    written.push('jsconfig.json');
  }
  return written;
}

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { atlasGroups, groupRank } from '../src/runtime/cf/atlas.ts';

const GUI = `<gui>
  <themes>
    <theme type="button" name=".btn_a[state='0']"><![CDATA[background-image: url(buttons/a.png);]]></theme>
    <theme type="button" name=".btn_a[state='1']"><![CDATA[background-image: url(buttons/a-down.png);]]></theme>
    <theme type="button" name=".btn_a_light[state='0']"><![CDATA[background-image: url(buttons/a-light.png);]]></theme>
    <theme type="background" name=".bg_dots"><![CDATA[background-image: url(tile-dots.png); background-repeat: repeat;]]></theme>
  </themes>
  <page name="Home">
    <portrait>
      <img x="0" y="0" w="10" h="10">icons/home.png</img>
      <btn x="0" y="0" w="10" h="10" t="btn_a" tags="iva_t_1" />
      <subpage name="menu" x="0" y="0" />
      <list x="0" y="0" w="10" h="10" contentSub="row" />
    </portrait>
  </page>
  <page name="Other">
    <portrait>
      <subpage name="menu" x="0" y="0" />
      <img x="0" y="0" w="10" h="10" j="7">icons/lamp-off.png</img>
    </portrait>
  </page>
  <subpage name="menu" w="10" h="10" t="bg_dots">
    <img x="0" y="0" w="10" h="10">icons/menu.png</img>
  </subpage>
  <subpage name="row" w="10" h="10">
    <img x="0" y="0" w="10" h="10">icons/row.png</img>
  </subpage>
  <subpage name="row__light" w="10" h="10">
    <img x="0" y="0" w="10" h="10">icons/row-light.png</img>
  </subpage>
  <subpage name="popup" w="10" h="10">
    <img x="0" y="0" w="10" h="10">icons/popup.png</img>
  </subpage>
  <subpage name="iva_theme_images" w="1" h="1" clip="1">
    <img x="0" y="0" w="1" h="1" j="0">icons/lamp-off-light.png</img>
  </subpage>
</gui>`;

// the looks' table, as themes.ts writes it into iva-themes.js
const LOOKS = `// iva: runtime themes (<Project themes>). Generated by iva.
var IvaTheme = (function () {
  var D = ${JSON.stringify({ names: ['dark', 'light'], tags: { iva_t_1: ['btn_a', 'btn_a_light'] }, images: { s7: ['icons/lamp-off.png', 'icons/lamp-off-light.png'] }, files: [], rows: [] })};
  var current = D.names[0];
})();
`;

test("images go in sheets with the page that shows them - its themes' every state and every look, its subpages', its lists' rows; several pages': shared; a tiled one: on its own", () => {
  const { groups, tiled } = atlasGroups(GUI, [LOOKS]);
  assert.deepEqual(Object.fromEntries([...groups].sort()), {
    'buttons/a-down.png': 'page:Home',
    'buttons/a-light.png': 'page:Home',
    'buttons/a.png': 'page:Home',
    'icons/home.png': 'page:Home',
    'icons/lamp-off-light.png': 'page:Other',
    'icons/lamp-off.png': 'page:Other',
    'icons/menu.png': 'shared',
    'icons/popup.png': 'sub:popup',
    'icons/row-light.png': 'page:Home',
    'icons/row.png': 'page:Home',
  });
  assert.deepEqual([...tiled], ['tile-dots.png']);
});

test("the sheets in order: the shared ones, the pages' as the .gui has them, the subpages' and the rest", () => {
  const { groups, pages } = atlasGroups(GUI, [LOOKS]);
  assert.deepEqual(pages, ['Home', 'Other']);
  const order = [...new Set(groups.values())].sort((a, b) => groupRank(a, pages) - groupRank(b, pages) || a.localeCompare(b));
  assert.deepEqual(order, ['shared', 'page:Home', 'page:Other', 'sub:popup']);
});

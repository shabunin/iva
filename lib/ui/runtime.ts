/**
 * What iva/ui components do on the panel: one iViewer script (ES5 - the
 * panel's JavaScript), shipped once when a component needs it. Components
 * wire themselves up with <OnStart js="IvaUI.xxx(...)" />.
 */
export const UI_RUNTIME = `// iva/ui runtime: what iva/ui components do on the panel. Generated by iva.
var IvaUI = (function () {
  var groups = {};
  var steppers = {};
  function pad(n) { return (n < 10 ? '0' : '') + n; }
  function fmt(v, decimals, unit) {
    var s = Number(v).toFixed(decimals || 0);
    if (!unit) return s;
    return unit.charAt(0) === '\\u00B0' ? s + unit : s + ' ' + unit;
  }
  function clamp(v, min, max) { return v < min ? min : v > max ? max : v; }
  // analog joins run 0..65535; min..max is what they stand for
  function toJoin(v, min, max) { return Math.round(clamp((v - min) / ((max - min) || 1), 0, 1) * 65535); }
  function fromJoin(j, min, max) { return min + (Number(j) || 0) / 65535 * (max - min); }
  return {
    /** a serial join showing the time (HH:MM) */
    clock: function (join) {
      function tick() { var d = new Date(); CF.setJoin(join, pad(d.getHours()) + ':' + pad(d.getMinutes())); }
      tick();
      setInterval(tick, 5000);
    },
    /** a serial join showing an analog join's value, as min..max */
    value: function (join, text, unit, decimals, min, max) {
      CF.watch(CF.JoinChangeEvent, join, function (j, v) { CF.setJoin(text, fmt(fromJoin(v, min, max), decimals, unit)); }, true);
    },
    /** an analog join set to a value in min..max */
    set: function (join, value, min, max) { CF.setJoin(join, toJoin(value, min, max)); },
    /** a stepper: the value in an analog join (min..max as 0..65535), shown in a serial join */
    stepper: function (id, join, text, o) {
      steppers[id] = { join: join, text: text, o: o, v: o.value };
      IvaUI.step(id, 0);
    },
    step: function (id, dir) {
      var s = steppers[id];
      if (!s) return;
      var o = s.o;
      s.v = clamp(Math.round((s.v + dir * o.step) / o.step) * o.step, o.min, o.max);
      CF.setJoin(s.join, toJoin(s.v, o.min, o.max));
      CF.setJoin(s.text, fmt(s.v, o.decimals, o.unit));
    },
    /** one of several (segmented, scenes): the index in an analog join, each option's digital join on when chosen */
    group: function (id, value, joins, initial) {
      groups[id] = { value: value, joins: joins };
      CF.watch(CF.JoinChangeEvent, value, function (j, v) {
        for (var i = 0; i < joins.length; i++) CF.setJoin(joins[i], i == v ? 1 : 0);
      }, true);
      if (initial !== undefined) IvaUI.pick(id, initial);
    },
    pick: function (id, i) {
      var g = groups[id];
      if (!g) return;
      CF.setJoin(g.value, i);
      for (var k = 0; k < g.joins.length; k++) CF.setJoin(g.joins[k], k == i ? 1 : 0);
    },
    /** side menu: the item of the page shown is on */
    menu: function (pages) {
      function show(page) { for (var p in pages) CF.setJoin(pages[p], p === page ? 1 : 0); }
      // iViewer passes (from, to, orientation); some runtimes just (to)
      CF.watch(CF.PageFlipEvent, function (a, b) { show(typeof b === 'string' ? b : a); });
      if (CF.currentPage) show(CF.currentPage);
    },
    /** a digital join off */
    off: function (join) { CF.setJoin(join, 0); }
  };
})();
`;

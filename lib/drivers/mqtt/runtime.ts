/**
 * What the Mqtt driver does on the panel: an MQTT 3.1.1 client written by
 * hand over an iViewer TCP system (one script, iva-mqtt.js, shipped once).
 * Bytes travel as strings a char a byte: CF.send() sends them so, and the
 * system's catch-all feedback hands what comes in to IvaMqtt as it comes.
 * No backticks in here: the script is a template literal.
 */
export const MQTT_RUNTIME = `// iva/drivers/mqtt runtime: an MQTT 3.1.1 client on an iViewer TCP system. Generated by iva.
var IvaMqtt = (function () {
  // ── bytes: strings a char a byte ─────────────────────────────────
  /** text as UTF-8 bytes */
  function utf8(s) {
    var out = '';
    for (var i = 0; i < s.length; i++) {
      var c = s.charCodeAt(i);
      if (c >= 0xd800 && c < 0xdc00 && i + 1 < s.length) c = 0x10000 + ((c - 0xd800) << 10) + (s.charCodeAt(++i) - 0xdc00);
      if (c < 0x80) out += String.fromCharCode(c);
      else if (c < 0x800) out += String.fromCharCode(0xc0 | (c >> 6), 0x80 | (c & 0x3f));
      else if (c < 0x10000) out += String.fromCharCode(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 0x3f), 0x80 | (c & 0x3f));
      else out += String.fromCharCode(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 0x3f), 0x80 | ((c >> 6) & 0x3f), 0x80 | (c & 0x3f));
    }
    return out;
  }
  /** UTF-8 bytes as text (bytes that aren't UTF-8: as they are, a char a byte) */
  function text(b) {
    var out = '', i = 0, n = b.length;
    while (i < n) {
      var c = b.charCodeAt(i++);
      if (c < 0x80) { out += String.fromCharCode(c); continue; }
      var extra = c >= 0xf0 ? 3 : c >= 0xe0 ? 2 : c >= 0xc0 ? 1 : 0;
      if (!extra || i + extra > n) return b;
      var cp = c & (extra === 3 ? 0x07 : extra === 2 ? 0x0f : 0x1f);
      for (var k = 0; k < extra; k++) {
        var d = b.charCodeAt(i + k);
        if ((d & 0xc0) !== 0x80) return b;
        cp = (cp << 6) | (d & 0x3f);
      }
      i += extra;
      if (cp >= 0x10000) { cp -= 0x10000; out += String.fromCharCode(0xd800 + (cp >> 10), 0xdc00 + (cp & 0x3ff)); }
      else out += String.fromCharCode(cp);
    }
    return out;
  }
  function u16(n) { return String.fromCharCode((n >> 8) & 0xff, n & 0xff); }
  function readU16(b, at) { return (b.charCodeAt(at) << 8) | b.charCodeAt(at + 1); }
  /** an MQTT string: its length, then its UTF-8 */
  function str(s) { var b = utf8(s); return u16(b.length) + b; }
  function readStr(b, at) { var n = readU16(b, at); return { value: text(b.slice(at + 2, at + 2 + n)), end: at + 2 + n }; }
  /** the remaining length: 7 bits a byte, the high bit saying another follows */
  function varint(n) {
    var out = '';
    do {
      var d = n % 128;
      n = Math.floor(n / 128);
      out += String.fromCharCode(n > 0 ? d | 0x80 : d);
    } while (n > 0);
    return out;
  }
  function packet(type, flags, body) { return String.fromCharCode((type << 4) | flags) + varint(body.length) + body; }

  // ── the packets ──────────────────────────────────────────────────
  var NAMES = { 1: 'connect', 2: 'connack', 3: 'publish', 4: 'puback', 5: 'pubrec', 6: 'pubrel', 7: 'pubcomp', 8: 'subscribe', 9: 'suback', 10: 'unsubscribe', 11: 'unsuback', 12: 'pingreq', 13: 'pingresp', 14: 'disconnect' };
  var encode = {
    /** { clientId, user, password, keepalive, clean } */
    connect: function (o) {
      var user = o.user !== undefined && o.user !== null && o.user !== '';
      var password = o.password !== undefined && o.password !== null && o.password !== '';
      // a password goes with a user name (an empty one if none was given)
      var flags = (o.clean === false ? 0 : 0x02) | (user || password ? 0x80 : 0) | (password ? 0x40 : 0);
      var body = str('MQTT') + String.fromCharCode(4, flags) + u16(o.keepalive || 0) + str(o.clientId || '');
      if (flags & 0x80) body += str(user ? String(o.user) : '');
      if (flags & 0x40) body += str(String(o.password));
      return packet(1, 0, body);
    },
    connack: function (code, sessionPresent) { return packet(2, 0, String.fromCharCode(sessionPresent ? 1 : 0, code || 0)); },
    /** topic, the payload's bytes, { qos, retain, dup, id } */
    publish: function (topic, payload, o) {
      o = o || {};
      var qos = o.qos || 0;
      return packet(3, (o.dup ? 0x08 : 0) | (qos << 1) | (o.retain ? 1 : 0), str(topic) + (qos ? u16(o.id) : '') + payload);
    },
    puback: function (id) { return packet(4, 0, u16(id)); },
    /** id, [{ filter, qos }] */
    subscribe: function (id, topics) {
      var body = u16(id);
      for (var i = 0; i < topics.length; i++) body += str(topics[i].filter) + String.fromCharCode(topics[i].qos || 0);
      return packet(8, 2, body);
    },
    suback: function (id, codes) { return packet(9, 0, u16(id) + String.fromCharCode.apply(null, codes)); },
    unsubscribe: function (id, filters) {
      var body = u16(id);
      for (var i = 0; i < filters.length; i++) body += str(filters[i]);
      return packet(10, 2, body);
    },
    unsuback: function (id) { return packet(11, 0, u16(id)); },
    pingreq: function () { return packet(12, 0, ''); },
    pingresp: function () { return packet(13, 0, ''); },
    disconnect: function () { return packet(14, 0, ''); }
  };
  /** one packet's fields from its type, flags and body */
  function decode(type, flags, body) {
    var p = { type: type, name: NAMES[type] || 'unknown' }, at, s;
    switch (type) {
      case 1:
        s = readStr(body, 0);
        p.protocol = s.value;
        p.level = body.charCodeAt(s.end);
        var f = body.charCodeAt(s.end + 1);
        p.clean = !!(f & 0x02);
        p.keepalive = readU16(body, s.end + 2);
        s = readStr(body, s.end + 4);
        p.clientId = s.value;
        if (f & 0x80) { s = readStr(body, s.end); p.user = s.value; }
        if (f & 0x40) { s = readStr(body, s.end); p.password = s.value; }
        break;
      case 2:
        p.sessionPresent = !!(body.charCodeAt(0) & 1);
        p.code = body.charCodeAt(1);
        break;
      case 3:
        p.dup = !!(flags & 0x08);
        p.qos = (flags >> 1) & 3;
        p.retain = !!(flags & 1);
        s = readStr(body, 0);
        p.topic = s.value;
        at = s.end;
        if (p.qos) { p.id = readU16(body, at); at += 2; }
        p.payload = body.slice(at);
        break;
      case 4: case 5: case 6: case 7: case 11:
        p.id = readU16(body, 0);
        break;
      case 8:
        p.id = readU16(body, 0);
        p.topics = [];
        for (at = 2; at < body.length;) { s = readStr(body, at); p.topics.push({ filter: s.value, qos: body.charCodeAt(s.end) }); at = s.end + 1; }
        break;
      case 9:
        p.id = readU16(body, 0);
        p.codes = [];
        for (at = 2; at < body.length; at++) p.codes.push(body.charCodeAt(at));
        break;
      case 10:
        p.id = readU16(body, 0);
        p.filters = [];
        for (at = 2; at < body.length;) { s = readStr(body, at); p.filters.push(s.value); at = s.end; }
        break;
    }
    return p;
  }
  /** the packets whole in a byte string, and what's left of one cut short (TCP reads split and merge them) */
  function parse(buf) {
    var packets = [], i = 0;
    while (i < buf.length) {
      var head = buf.charCodeAt(i), len = 0, mult = 1, j = i + 1;
      for (;;) {
        if (j >= buf.length) return { packets: packets, rest: buf.slice(i) };
        var d = buf.charCodeAt(j++);
        len += (d & 0x7f) * mult;
        if (!(d & 0x80)) break;
        mult *= 128;
        if (mult > 128 * 128 * 128) throw new Error('mqtt: bad remaining length');
      }
      if (j + len > buf.length) return { packets: packets, rest: buf.slice(i) };
      packets.push(decode(head >> 4, head & 0x0f, buf.slice(j, j + len)));
      i = j + len;
    }
    return { packets: packets, rest: '' };
  }

  // ── topics ───────────────────────────────────────────────────────
  /** does a filter (+ a level, # the rest) take the topic; a leading wildcard takes no $SYS topic */
  function matches(filter, topic) {
    if (filter === topic) return true;
    var f = filter.split('/'), t = topic.split('/');
    for (var i = 0; i < f.length; i++) {
      if (f[i] === '#') return i > 0 || topic.charAt(0) !== '$';
      if (i >= t.length) return false;
      if (f[i] === '+') { if (i === 0 && topic.charAt(0) === '$') return false; continue; }
      if (f[i] !== t[i]) return false;
    }
    return f.length === t.length;
  }

  // ── joins and payloads ───────────────────────────────────────────
  function clamp(v, min, max) { return v < min ? min : v > max ? max : v; }
  var RANGE = [0, 65535];
  /** a field out of a JSON payload: 'value', 'state.on', 'readings.0.t' */
  function pick(payload, path) {
    var v;
    try { v = JSON.parse(payload); } catch (e) { return undefined; }
    var keys = path.split('.');
    for (var i = 0; i < keys.length; i++) {
      if (v === null || typeof v !== 'object') return undefined;
      v = v[keys[i]];
    }
    return v;
  }
  var ON = { '1': 1, 'true': 1, 'on': 1, '0': 0, 'false': 0, 'off': 0 };
  /** a payload (text, or a field of it) as the join's value; undefined: nothing for the join */
  function toJoin(sub, payload) {
    var raw = payload;
    if (sub.path) { raw = pick(payload, sub.path); if (raw === undefined) return undefined; }
    if (sub.type === 'd') {
      if (typeof raw === 'boolean') return raw ? 1 : 0;
      var w = String(raw).trim().toLowerCase();
      if (ON[w] !== undefined) return ON[w];
      var n = Number(w);
      return isFinite(n) && w !== '' ? (n ? 1 : 0) : undefined;
    }
    if (sub.type === 'a') {
      var x = typeof raw === 'number' ? raw : parseFloat(String(raw));
      if (!isFinite(x)) return undefined;
      var r = sub.range || RANGE;
      return Math.round(clamp((x - r[0]) / ((r[1] - r[0]) || 1), 0, 1) * 65535);
    }
    return typeof raw === 'string' ? raw : typeof raw === 'object' ? JSON.stringify(raw) : String(raw);
  }
  /** a join's value as the payload: on / off words, the number in its range, the text; through the template */
  function toPayload(pub, v) {
    var out;
    if (pub.type === 'd') out = Number(v) ? (pub.on === undefined ? '1' : pub.on) : (pub.off === undefined ? '0' : pub.off);
    else if (pub.type === 'a') {
      var r = pub.range || RANGE;
      var x = r[0] + (Number(v) || 0) / 65535 * (r[1] - r[0]);
      out = pub.decimals === undefined ? String(Math.round(x)) : x.toFixed(pub.decimals);
    } else out = String(v);
    return pub.template ? pub.template.split('{value}').join(out) : out;
  }

  // ── the brokers, one a system ────────────────────────────────────
  var brokers = {};
  /** what the driver last wrote to each join: its change event isn't published back */
  var written = {};
  function log(b, line) {
    if (!b.o.log) return;
    b.lines.push(line);
    while (b.lines.length > (b.o.logLines || 8)) b.lines.shift();
    CF.setJoin(b.o.log, b.lines.join('\\n'));
  }
  function status(b, s) { b.status = s; if (b.o.status) CF.setJoin(b.o.status, s); }
  function send(b, bytes) { CF.send(b.system, bytes); }
  function nextId(b) { var id = b.nextId; b.nextId = id >= 65535 ? 1 : id + 1; return id; }
  /** SUBSCRIBE these filters (each once, at the highest QoS asked) */
  function subscribe(b, subs) {
    if (!b.connected || !subs.length) return;
    var qos = {}, filters = [];
    for (var i = 0; i < subs.length; i++) {
      var f = subs[i].filter;
      if (qos[f] === undefined) filters.push(f);
      qos[f] = Math.max(qos[f] || 0, subs[i].qos || 0);
    }
    var id = nextId(b);
    b.subscribing[id] = filters;
    send(b, encode.subscribe(id, filters.map(function (f) { return { filter: f, qos: qos[f] }; })));
  }
  function publish(b, topic, payload, o) {
    o = o || {};
    var qos = o.qos ? 1 : 0;
    var p = { topic: topic, payload: utf8(String(payload)), qos: qos, retain: !!o.retain };
    if (qos) {
      p.id = nextId(b);
      b.pending[p.id] = p; // till its PUBACK; sent again (dup) on the next connect if none comes
    }
    if (!b.connected) {
      if (!qos) log(b, '> ' + topic + ': ' + payload + ' (not connected: dropped)');
      return;
    }
    send(b, encode.publish(topic, p.payload, p));
    log(b, '> ' + topic + ': ' + payload);
  }
  function stopPing(b) { if (b.timer) { clearInterval(b.timer); b.timer = null; } b.awaitPing = false; }
  /** the link gone quiet (no PINGRESP in a keepalive): the system started over, so it connects again */
  function dead(b) {
    stopPing(b);
    b.connected = false;
    status(b, 'Disconnected');
    log(b, 'no answer to a ping: connecting again');
    CF.setSystemProperties(b.system, { enabled: false });
    setTimeout(function () { CF.setSystemProperties(b.system, { enabled: true }); }, 300);
  }
  function startPing(b) {
    stopPing(b);
    var keepalive = Number(b.o.keepalive) || 0;
    if (!keepalive) return;
    b.timer = setInterval(function () {
      if (!b.connected) return;
      if (b.awaitPing) return dead(b);
      b.awaitPing = true;
      send(b, encode.pingreq());
    }, keepalive * 1000);
  }
  function onConnack(b, p) {
    if (p.code !== 0) {
      status(b, 'Refused (code ' + p.code + ')');
      log(b, 'the broker refused the connection: code ' + p.code);
      return;
    }
    b.connected = true;
    status(b, 'Connected');
    subscribe(b, b.subs);
    // QoS 1 publishes still unanswered: again, as duplicates
    for (var id in b.pending) {
      var q = b.pending[id];
      q.dup = true;
      send(b, encode.publish(q.topic, q.payload, q));
      log(b, '> ' + q.topic + ': ' + text(q.payload) + ' (again)');
    }
    startPing(b);
  }
  function onPublish(b, p) {
    if (p.qos === 1) send(b, encode.puback(p.id));
    var payload = text(p.payload);
    log(b, '< ' + p.topic + ': ' + payload);
    for (var i = 0; i < b.subs.length; i++) {
      var sub = b.subs[i];
      if (!matches(sub.filter, p.topic)) continue;
      if (sub.handler) { sub.handler(p.topic, payload, p); continue; }
      var v = toJoin(sub, payload);
      if (v === undefined) continue;
      written[sub.join] = String(v);
      CF.setJoin(sub.join, v);
    }
  }
  function handle(b, p) {
    switch (p.name) {
      case 'connack': onConnack(b, p); break;
      case 'publish': onPublish(b, p); break;
      case 'puback': delete b.pending[p.id]; break;
      case 'suback':
        var filters = b.subscribing[p.id] || [];
        delete b.subscribing[p.id];
        for (var i = 0; i < p.codes.length; i++) if (p.codes[i] === 0x80) log(b, 'subscription refused: ' + filters[i]);
        break;
      case 'pingresp': b.awaitPing = false; break;
    }
  }
  /** what the system's feedback handed over: packets as they complete */
  function feed(b, data) {
    if (!data) return;
    b.rx += data;
    var r;
    try { r = parse(b.rx); } catch (e) { b.rx = ''; log(b, String(e && e.message || e)); return; }
    b.rx = r.rest;
    for (var i = 0; i < r.packets.length; i++) handle(b, r.packets[i]);
  }
  function up(b) {
    b.rx = '';
    b.connected = false;
    stopPing(b);
    status(b, 'Connecting');
    send(b, encode.connect({ clientId: b.o.clientId || 'iva', user: b.o.user, password: b.o.password, keepalive: Number(b.o.keepalive) || 0, clean: b.o.clean }));
  }
  function down(b) {
    b.rx = '';
    b.connected = false;
    stopPing(b);
    // a refusal stays on show: the broker closes after it, and the system will try again
    if (b.status.indexOf('Refused') !== 0) status(b, 'Disconnected');
  }
  function broker(system) {
    var b = brokers[system];
    if (b) return b;
    b = brokers[system] = { system: system, o: {}, subs: [], connected: false, rx: '', nextId: 1, pending: {}, subscribing: {}, lines: [], timer: null, awaitPing: false, status: '' };
    CF.watch(CF.FeedbackMatchedEvent, system, 'frame', function (name, data) { feed(b, data); });
    CF.watch(CF.ConnectionStatusChangeEvent, system, function (name, connected) { if (connected) up(b); else down(b); });
    return b;
  }
  /** a publish binding: the join's changes to the topic (the driver's own writes to it skipped) */
  function bind(b, pub) {
    CF.watch(CF.JoinChangeEvent, pub.join, function (j, v) {
      var w = written[j];
      delete written[j];
      if (w !== undefined && w === String(v)) return;
      publish(b, pub.topic, toPayload(pub, v), pub);
    });
  }

  return {
    // the codec, for scripts of your own: IvaMqtt.encode.publish('t', IvaMqtt.utf8('hi')) ...
    encode: encode, decode: decode, parse: parse, matches: matches, utf8: utf8, text: text, toJoin: toJoin, toPayload: toPayload,
    /**
     * what <Mqtt> emits: the broker on this system, with { clientId, user,
     * password, keepalive, clean, status, log, logLines } and its bindings -
     * subscribe: { 'home/lamp': { join, type: 'd' | 'a' | 's', path, range, qos } },
     * publish: { 'home/lamp/set': { join, type, on, off, range, decimals, template, qos, retain } }.
     * Several calls for one system add up (the connection's options from whichever gives them).
     */
    add: function (system, o) {
      var b = broker(system);
      o = o || {};
      var keys = ['clientId', 'user', 'password', 'keepalive', 'clean', 'status', 'log', 'logLines'];
      for (var i = 0; i < keys.length; i++) if (o[keys[i]] !== undefined) b.o[keys[i]] = o[keys[i]];
      var added = [];
      for (var filter in o.subscribe || {}) {
        var sub = o.subscribe[filter];
        sub.filter = filter;
        b.subs.push(sub);
        added.push(sub);
      }
      for (var topic in o.publish || {}) {
        var pub = o.publish[topic];
        pub.topic = topic;
        bind(b, pub);
      }
      subscribe(b, added);
      if (!b.status) status(b, 'Connecting');
    },
    /** a script's own subscription: handler(topic, payload) for what matches the filter */
    subscribe: function (system, filter, handler, qos) {
      var b = broker(system);
      var sub = { filter: filter, handler: handler, qos: qos || 0 };
      b.subs.push(sub);
      subscribe(b, [sub]);
    },
    /** a message from a script: IvaMqtt.publish('mqtt', 'home/say', 'hello', { qos: 1, retain: true }) */
    publish: function (system, topic, payload, o) { publish(broker(system), topic, payload, o); },
    /** another broker (or the same one afresh): the system's address changed and started over */
    reconnect: function (system, host, port) {
      var b = broker(system);
      stopPing(b);
      b.connected = false;
      var changes = { enabled: false };
      if (host) changes.address = host;
      if (port) changes.port = Number(port);
      CF.setSystemProperties(system, changes);
      status(b, 'Connecting');
      setTimeout(function () { CF.setSystemProperties(system, { enabled: true }); }, 300);
    },
    /** a broker's state (tests): { connected, status, subs, pending } */
    broker: function (system) { return brokers[system]; }
  };
})();
`;
